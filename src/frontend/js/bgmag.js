/** Date → 소수 연도(예: 2026.84) */
export function decimalYear(date) {
  const y = date.getUTCFullYear();
  const a = Date.UTC(y, 0, 1), b = Date.UTC(y + 1, 0, 1);
  return y + (+date - a) / (b - a);
}

/** 편각(도, 동쪽 +). lat · lon = 측지 위도 · 경도(도), altKm = 해발 고도(km), year = 소수 연도 */
export function declinationAt(lat, lon, altKm, year) {
  const A = 6378.137, B = 6356.7523142, RE = 6371.2;   // WGS84 장반경 · 단반경, 지구 평균 반경(km)
  const a2 = A * A, b2 = B * B, c2 = a2 - b2, a4 = a2 * a2, b4 = b2 * b2, c4 = a4 - b4;
  const slat = Math.sin(lat * RAD), clat = Math.cos(lat * RAD), slat2 = slat * slat, clat2 = clat * clat;
  // 측지 → 지구 중심 구면 좌표
  const q = Math.sqrt(a2 - c2 * slat2), q1 = altKm * q, q2 = ((q1 + a2) / (q1 + b2)) ** 2;
  const ct = slat / Math.sqrt(q2 * clat2 + slat2), st = Math.sqrt(1 - ct * ct);
  const r = Math.sqrt(altKm * altKm + 2 * q1 + (a4 - c4 * slat2) / (q * q));
  const d = Math.sqrt(a2 * clat2 + b2 * slat2);
  const ca = (altKm + d) / r, sa = c2 * clat * slat / (r * d);
  const dt = year - EPOCH;
  // 가우스 정규화 르장드르 함수 P · 도함수 dP
  const P = [], dP = [];
  for (let n = 0; n <= N; n++) { P.push(new Float64Array(N + 1)); dP.push(new Float64Array(N + 1)); }
  P[0][0] = 1;
  const cosm = [], sinm = [];
  for (let m = 0; m <= N; m++) { cosm.push(Math.cos(m * lon * RAD)); sinm.push(Math.sin(m * lon * RAD)); }
  let br = 0, bt = 0, bp = 0, ar = RE / r, par = ar * ar;
  for (let n = 1; n <= N; n++) {
    par *= ar;   // (RE / r) ^ (n + 2)
    for (let m = 0; m <= n; m++) {
      if (n === m) {
        P[n][m] = st * P[n - 1][m - 1];
        dP[n][m] = st * dP[n - 1][m - 1] + ct * P[n - 1][m - 1];
      } else if (n === 1 && m === 0) {
        P[1][0] = ct;
        dP[1][0] = -st;
      } else {
        const K = n > 1 ? ((n - 1) ** 2 - m * m) / ((2 * n - 1) * (2 * n - 3)) : 0;
        const p2 = n - 2 >= m ? P[n - 2][m] : 0, dp2 = n - 2 >= m ? dP[n - 2][m] : 0;
        P[n][m] = ct * P[n - 1][m] - K * p2;
        dP[n][m] = ct * dP[n - 1][m] - st * P[n - 1][m] - K * dp2;
      }
      const g = (G0[n][m] + dt * GD[n][m]) * S[n][m], h = (H0[n][m] + dt * HD[n][m]) * S[n][m];
      const t1 = g * cosm[m] + h * sinm[m], t2 = g * sinm[m] - h * cosm[m];
      bt -= par * t1 * dP[n][m];
      bp += m * t2 * par * P[n][m];
      br += (n + 1) * t1 * par * P[n][m];
    }
  }
  bp = st > 1e-9 ? bp / st : 0;   // 극점에서는 편각이 정의되지 않는다(쓸 일 없음)
  const bx = -bt * ca - br * sa, by = bp;
  return Math.atan2(by, bx) / RAD;
}

/** 지금 이 자리의 편각(라디안, 동쪽 +) — 해발 0 으로 계산(Stardroid 와 같음. 위치 권한은 고도를 주지 않을 수 있다) */
export function declinationRad(lat, lon, date = new Date()) {
  return declinationAt(lat, lon, 0, decimalYear(date)) * RAD;
}
